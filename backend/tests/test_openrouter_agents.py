def test_openrouter_unconfigured_raises_unavailable():
    service = OpenRouterService(api_key="")
    assert not service.is_configured()

    with pytest.raises(OpenRouterUnavailableError, match="not configured"):
        service.generate_text("Explain photosynthesis")


def test_openrouter_mock_successful_generation():
    service = OpenRouterService(api_key="sk-or-v1-mock-test-key", model_name="meta-llama/llama-3.3-70b-instruct:free")
    assert service.is_configured()

    mock_response = MagicMock()
    mock_response.status_code = 200
    mock_response.json.return_value = {
        "choices": [
            {
                "message": {
                    "role": "assistant",
                    "content": "Deep conceptual breakdown generated by OpenRouter Free Tier model."
                }
            }
        ]
    }

    with patch("httpx.Client") as mock_client_cls:
        mock_client = MagicMock()
        mock_client.__enter__.return_value = mock_client
        mock_client.post.return_value = mock_response
        mock_client_cls.return_value = mock_client

        output = service.generate_text("Synthesize a clinical trial summary")
        assert "OpenRouter Free Tier model" in output
        mock_client.post.assert_called_once()
        call_kwargs = mock_client.post.call_args[1]
        assert call_kwargs["headers"]["Authorization"] == "Bearer sk-or-v1-mock-test-key"
        assert call_kwargs["json"]["model"] == "meta-llama/llama-3.3-70b-instruct:free"


