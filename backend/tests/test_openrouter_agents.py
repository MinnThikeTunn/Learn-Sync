def test_orchestrator_parallel_fan_out(base_context):
    """
    Tests parallel concurrent execution: orchestrator spawns and executes
    all 4 subagents simultaneously via ThreadPoolExecutor.
    """
    artifacts_map = learner_agent_orchestrator.spawn_all_subagents(base_context, max_workers=4)

    assert len(artifacts_map) == 4
    assert LearningStyle.VISUAL in artifacts_map
    assert LearningStyle.AUDITORY in artifacts_map
    assert LearningStyle.READ_WRITE in artifacts_map
    assert LearningStyle.KINESTHETIC in artifacts_map

    # Validate distinct artifacts synthesized by distinct subagents
    assert artifacts_map[LearningStyle.VISUAL].artifact_type == StudyArtifactType.MIND_MAP
    assert artifacts_map[LearningStyle.AUDITORY].artifact_type == StudyArtifactType.AUDIO_SCRIPT
    assert artifacts_map[LearningStyle.READ_WRITE].artifact_type == StudyArtifactType.SUMMARY_NOTE
    assert artifacts_map[LearningStyle.KINESTHETIC].artifact_type == StudyArtifactType.CLINICAL_SIMULATION


def test_adaptive_learning_engine_generate_all_artifacts_integration():
    """
    Tests AdaptiveLearningEngine.generate_all_artifacts endpoint integration.
    """
    f_id = uuid.uuid4()
    chunks = [
        {
            "id": uuid.uuid4(),
            "content": "Patient triage protocol and clinical presentation in myocardial infarction.",
            "cosine_similarity": 0.89,
        }
    ]

    all_artifacts = AdaptiveLearningEngine.generate_all_artifacts(
        folder_id=f_id,
        mode=WorkloadMode.FREE,
        topic="Myocardial Infarction",
        chunks=chunks,
    )

    assert len(all_artifacts) == 4
    for style, artifact in all_artifacts.items():
        assert artifact.folder_id == f_id
        assert artifact.learning_style == style
        assert artifact.topic == "Myocardial Infarction"
        assert not artifact.is_low_confidence
